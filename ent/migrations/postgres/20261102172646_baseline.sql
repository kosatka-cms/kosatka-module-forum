-- Create "forum_settings" table
CREATE TABLE "forum_settings" ("id" bigint NOT NULL, "vocabulary_id" bigint NULL, PRIMARY KEY ("id"), CONSTRAINT "forum_settings_taxonomy_vocabulary_vocabulary" FOREIGN KEY ("vocabulary_id") REFERENCES "taxonomy_vocabulary" ("id") ON DELETE SET NULL);
-- Create index "forumsettings_vocabulary_id" to table: "forum_settings"
CREATE INDEX "forumsettings_vocabulary_id" ON "forum_settings" ("vocabulary_id");
-- Create "forum_stats" table
CREATE TABLE "forum_stats" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "sticky" bigint NOT NULL DEFAULT 0, "comment_count" bigint NOT NULL DEFAULT 0, "last_comment_at" timestamptz NOT NULL, "nid" bigint NOT NULL, PRIMARY KEY ("id"), CONSTRAINT "forum_stats_nodes_forum_stats" FOREIGN KEY ("nid") REFERENCES "nodes" ("id") ON DELETE CASCADE);
-- Create index "forum_stats_nid_key" to table: "forum_stats"
CREATE UNIQUE INDEX "forum_stats_nid_key" ON "forum_stats" ("nid");
-- Create index "forumstats_sticky" to table: "forum_stats"
CREATE INDEX "forumstats_sticky" ON "forum_stats" ("sticky");
-- Create index "forumstats_last_comment_at" to table: "forum_stats"
CREATE INDEX "forumstats_last_comment_at" ON "forum_stats" ("last_comment_at");
-- Create "forum_topics" table
CREATE TABLE "forum_topics" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "body" text NULL, "nid" bigint NOT NULL, PRIMARY KEY ("id"), CONSTRAINT "forum_topics_nodes_nodes" FOREIGN KEY ("nid") REFERENCES "nodes" ("id") ON DELETE CASCADE);
-- Create index "forum_topics_nid" to table: "forum_topics"
CREATE UNIQUE INDEX "forum_topics_nid" ON "forum_topics" ("nid");
